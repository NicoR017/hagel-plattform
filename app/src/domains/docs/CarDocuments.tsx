import { useCallback, useEffect, useRef, useState } from "react";
import { api, httpFetch } from "../../api";
import { shareOrDownload } from "../../shared/docs";
import { fmtDateTime, t, type Key } from "../../shared/i18n";
import type { LocalVehicle } from "../../shared/sync/db";
import { useField } from "../../shared/store";
import { toast } from "../../shared/toast";
import { Dialog, Field } from "../../shared/ui";
import { DossierDialog } from "./DossierDialog";

export interface DocView { id: string; category: string; type: string; title: string; number: string | null; amountHt: number | null; partnerId: string | null; partnerName: string; inDossier: boolean; version: number; hasFile: boolean; latest: boolean; createdAt: string }
export interface DocsData {
  documents: DocView[];
  generated: { receipts: { id: string; kind: string; signedAt: string; hasReceipt: boolean }[]; reports: { id: string; type: string; at: string; hasFile: boolean }[]; orders: { id: string; number: string; kind: string; status: string; hasPdf: boolean }[] };
  missing: { key: string; type: string; partnerId?: string }[];
  dossiers: { id: string; to: string[]; cc: string[]; status: string; at: string; included: string[]; missing: string[] }[];
}
const CATS = ["assessment", "repair", "parts", "paint", "other"] as const;
const errText = (e: unknown) => (e as Error).message || String(e);

async function openDoc(path: string, name: string, mime: string) {
  const r = await httpFetch("GET", path, undefined, { blob: true });
  if (r.status !== 200 || !r.blob) { toast(t("hoReceiptFailed"), 5000); return; }
  await shareOrDownload(r.blob, name, mime);
}

/** Documents of a car (tab "Documents" of the repair detail): grouped by Assessment · Repair · Spare parts · Paint · Other, generated by the app or imported, what is missing, import and the repair dossier. */
export function CarDocuments({ v }: { v: LocalVehicle }) {
  const f = useField();
  const [data, setData] = useState<DocsData | null>(null);
  const [imp, setImp] = useState<null | { type?: string; partnerId?: string }>(null);
  const [dossier, setDossier] = useState(false);
  const stamp = f.status.lastSyncAt ?? 0;
  const reload = useCallback(async () => { try { setData(await api<DocsData>("GET", `/vehicles/${v.id}/documents`)); } catch { setData(null); } }, [v.id]);
  useEffect(() => { if (navigator.onLine) void reload(); }, [reload, stamp]);
  const mayImport = f.can("documents.importer"), maySend = f.can("dossier.envoyer");
  if (!data) return navigator.onLine ? null : <p className="muted">{t("v4HistOnline")}</p>;
  const missLabel = (m: DocsData["missing"][number]) => `${t(`f6T_${m.type}` as Key)}${m.partnerId ? ` · ${f.refs?.bodyshops.find((b) => b.id === m.partnerId)?.name ?? ""}` : ""}`;
  const byCat = (cat: string) => data.documents.filter((d) => d.category === cat && d.latest);

  return (
    <section className="panel" style={{ padding: 16 }}>
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "baseline", flexWrap: "wrap", gap: 8, marginBottom: 10 }}>
        <h3 style={{ margin: 0 }}>📁 {t("f6DocsTitle")}</h3>
        <span style={{ display: "flex", gap: 6, flexWrap: "wrap" }}>
          {mayImport && <button className="chip on" style={{ minHeight: 44 }} onClick={() => setImp({})}>⬆ {t("f6Import")}</button>}
          {maySend && <button className="chip on" style={{ minHeight: 44 }} onClick={() => setDossier(true)}>✉ {t("f6SendDossier")}</button>}
        </span>
      </div>
      {CATS.map((cat) => {
        const imported = byCat(cat);
        const miss = data.missing.filter((m) => (cat === "parts" && m.type === "parts_invoice") || (cat === "paint" && m.type === "paint_invoice"));
        const gen: { key: string; label: string; sub?: string; open?: () => void }[] = [];
        if (cat === "repair") for (const h of data.generated.receipts) gen.push({ key: h.id, label: h.kind === "drop_off" ? t("f6Receipt_drop") : t("f6Receipt_pick"), sub: fmtDateTime(h.signedAt), open: h.hasReceipt ? () => void openDoc(`/handovers/${h.id}/receipt`, `${h.kind}.pdf`, "application/pdf") : undefined });
        if (cat === "assessment") for (const s of data.generated.reports.filter((x) => x.type === "kva")) gen.push({ key: s.id, label: `${t("f6ReportDoc")} · KVA`, sub: fmtDateTime(s.at) });
        if (cat === "repair") for (const s of data.generated.reports.filter((x) => x.type === "reparation")) gen.push({ key: s.id, label: `${t("f6ReportDoc")} · PDR`, sub: fmtDateTime(s.at) });
        if (cat === "parts") for (const o of data.generated.orders) gen.push({ key: o.id, label: `${t("f6OrderDoc")} ${o.number}`, sub: o.status, open: o.hasPdf ? () => void openDoc(`/parts/orders/${o.id}/pdf`, `${o.number}.pdf`, "application/pdf") : undefined });
        if (!imported.length && !miss.length && !gen.length) return null;
        return (
          <div key={cat} style={{ marginBottom: 12 }}>
            <div className="muted" style={{ fontSize: 12, fontWeight: 700, textTransform: "uppercase", margin: "6px 0" }}>{t(`f6Cat_${cat}` as Key)}</div>
            <ul style={{ listStyle: "none", margin: 0, padding: 0, display: "flex", flexDirection: "column", gap: 6 }}>
              {gen.map((g) => <li key={g.key} className="row" style={{ border: "1px solid var(--line)", borderRadius: 10, padding: "8px 10px", gap: 8 }}><span style={{ flex: 1 }}><b>{g.label}</b> <span className="muted" style={{ fontSize: 12 }}>· {g.sub} · {t("f6GeneratedBy")}</span></span>{g.open && <button className="chip" style={{ minHeight: 40 }} onClick={g.open}>{t("f6Open")}</button>}</li>)}
              {imported.map((d) => (
                <li key={d.id} className="row" style={{ border: "1px solid var(--line)", borderRadius: 10, padding: "8px 10px", gap: 8 }}>
                  <span style={{ flex: 1 }}><b>{d.title || t(`f6T_${d.type}` as Key)}{d.number ? ` · ${d.number}` : ""}</b>
                    <span className="muted" style={{ fontSize: 12, display: "block" }}>{t(`f6T_${d.type}` as Key)}{d.partnerName ? ` · ${d.partnerName}` : ""}{d.amountHt !== null ? ` · ${d.amountHt.toFixed(2)} €` : ""} · {t("f6Version").replace("{n}", String(d.version))} · {fmtDateTime(d.createdAt)}{d.inDossier ? " · ✉" : ""}</span></span>
                  {d.hasFile && <button className="chip" style={{ minHeight: 40 }} onClick={() => void openDoc(`/documents/${d.id}/file`, `${d.number || d.type}`, "application/octet-stream")}>{t("f6Open")}</button>}
                  {mayImport && (d.type === "parts_invoice" || d.type === "paint_invoice") && <button className="chip" style={{ minHeight: 40 }} onClick={() => setImp({ type: d.type, partnerId: d.partnerId ?? undefined })}>⬆</button>}
                </li>
              ))}
              {miss.map((m) => <li key={m.key} className="row" style={{ border: "1px dashed #E9C79A", background: "#FDF0E1", borderRadius: 10, padding: "8px 10px", gap: 8 }}><span style={{ flex: 1, color: "#8A4A06" }}><b>{missLabel(m)}</b> · {t("f6Missing")}</span>{mayImport && <button className="chip on" style={{ minHeight: 40 }} onClick={() => setImp({ type: m.type, partnerId: m.partnerId })}>{t("f6ImportMissing")}</button>}</li>)}
            </ul>
          </div>
        );
      })}
      {data.dossiers.length > 0 && (
        <div style={{ marginTop: 8 }}>
          <div className="muted" style={{ fontSize: 12, fontWeight: 700, textTransform: "uppercase" }}>{t("f6History")}</div>
          {data.dossiers.map((d) => <div key={d.id} style={{ fontSize: 13, padding: "4px 0" }}>✉ {fmtDateTime(d.at)} · {d.to.join(", ")} · {d.status === "sent" ? "✓" : "✕"}{d.missing.length ? ` · ${t("f6SentMissing").replace("{list}", d.missing.map((m) => t(`f6T_${m}` as Key)).join(", "))}` : ""}</div>)}
        </div>
      )}
      {imp && <ImportDialog v={v} initial={imp} orders={data.generated.orders} onClose={() => setImp(null)} onDone={() => { setImp(null); void reload(); }} />}
      {dossier && <DossierDialog v={v} onClose={() => setDossier(false)} onDone={() => { setDossier(false); void reload(); }} />}
    </section>
  );
}

/** D39: import a document: type, number and amount excl. VAT for an invoice, painter for a paint invoice, option to send it with the dossier; the file */
function ImportDialog({ v, initial, orders, onClose, onDone }: { v: LocalVehicle; initial: { type?: string; partnerId?: string }; orders: DocsData["generated"]["orders"]; onClose: () => void; onDone: () => void }) {
  const f = useField();
  const [type, setType] = useState(initial.type ?? "parts_invoice");
  const [number, setNumber] = useState(""), [amount, setAmount] = useState(""), [title, setTitle] = useState(""), [partner, setPartner] = useState(initial.partnerId ?? "");
  const [inDossier, setInDossier] = useState(true), [orderIds, setOrderIds] = useState<string[]>([]);
  const [busy, setBusy] = useState(false), [err, setErr] = useState("");
  const file = useRef<HTMLInputElement>(null);
  const invoice = type === "parts_invoice" || type === "paint_invoice";
  const partners = (f.refs?.bodyshops ?? []).filter((b) => b.paintPartner);
  const amountN = Number(amount.replace(",", "."));
  const ok = !busy && (!invoice || (!!number.trim() && amount.trim() !== "" && Number.isFinite(amountN) && amountN >= 0)) && (type !== "paint_invoice" || !!partner);
  const submit = async () => {
    const fl = file.current?.files?.[0];
    if (!fl) { setErr(t("f6ChooseFile")); return; }
    setBusy(true); setErr("");
    try {
      const d = await api<{ id: string }>("POST", `/vehicles/${v.id}/documents`, {
        type, ...(title.trim() ? { title: title.trim() } : {}), ...(invoice ? { number: number.trim(), amountHt: amountN } : {}), ...(type === "paint_invoice" ? { partnerId: partner } : {}),
        ...(type === "parts_invoice" && orderIds.length ? { orderIds } : {}), inDossier,
      });
      const r = await httpFetch("PUT", `/documents/${d.id}/file`, undefined, { raw: fl, contentType: fl.type || "application/octet-stream" });
      if (r.status !== 200) throw new Error((r.data as { message?: string })?.message || t("pdfFailed"));
      toast(t("f6Imported"), 4000);
      onDone();
    } catch (e) { setErr(errText(e)); setBusy(false); }
  };
  return (
    <Dialog title={t("f6ImportTitle")} onClose={onClose}>
      <Field label={t("f6Type")}>
        <select className="inp" value={type} onChange={(e) => setType(e.target.value)}>{["parts_invoice", "paint_invoice", "insurer_doc", "customer_doc", "photos", "other"].map((x) => <option key={x} value={x}>{t(`f6T_${x}` as Key)}</option>)}</select>
      </Field>
      {type === "paint_invoice" && <Field label={`${t("f6Painter")} *`}><select className="inp" value={partner} onChange={(e) => setPartner(e.target.value)}><option value="">{t("f5PartnerPh")}</option>{partners.map((p) => <option key={p.id} value={p.id}>{p.name}</option>)}</select></Field>}
      {invoice && (
        <div className="row" style={{ gap: 8 }}>
          <div className="grow"><Field label={`${t("f6Number")} *`}><input className="inp" value={number} maxLength={60} onChange={(e) => setNumber(e.target.value)} /></Field></div>
          <div className="grow"><Field label={`${t("f6Amount")} *`}><input className="inp" inputMode="decimal" value={amount} onChange={(e) => setAmount(e.target.value)} /></Field></div>
        </div>
      )}
      {!invoice && <Field label={t("f6TitleField")}><input className="inp" value={title} maxLength={160} onChange={(e) => setTitle(e.target.value)} /></Field>}
      {type === "parts_invoice" && orders.filter((o) => o.kind === "main" || o.kind === "complement").length > 0 && (
        <Field label={t("f6LinkOrders")}>{orders.filter((o) => o.kind === "main" || o.kind === "complement").map((o) => <label key={o.id} style={{ display: "flex", gap: 8, alignItems: "center", minHeight: 36 }}><input type="checkbox" style={{ width: 22, height: 22 }} checked={orderIds.includes(o.id)} onChange={() => setOrderIds((s) => (s.includes(o.id) ? s.filter((x) => x !== o.id) : [...s, o.id]))} /> {o.number}</label>)}</Field>
      )}
      <Field label={`${t("f6File")} *`}><input ref={file} type="file" accept="application/pdf,image/jpeg,image/png,.pdf,.jpg,.jpeg,.png" /></Field>
      <label style={{ display: "flex", gap: 8, alignItems: "center", margin: "6px 0" }}><input type="checkbox" style={{ width: 22, height: 22 }} checked={inDossier} onChange={(e) => setInDossier(e.target.checked)} /> {t("f6InDossier")}</label>
      {err && <div className="err">{err}</div>}
      <button className="pbtn" disabled={!ok} onClick={() => void submit()}>{busy ? t("f6Importing") : `⬆ ${t("f6Import")}`}</button>
    </Dialog>
  );
}
